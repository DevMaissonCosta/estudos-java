import java.util.Scanner;

public class ExercicioDivisaoPares {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        int N = sc.nextInt();
        int p1 = sc.nextInt();
        int p2 = sc.nextInt();

        for (int i=0; i<N; i++){
          if (p1 % p2 !=0);
            System.out.println();
        }

    }
}
